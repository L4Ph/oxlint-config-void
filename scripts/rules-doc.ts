import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { rules } from "../src/plugin/index.ts";

type Planned = { name: string; family: string };
type Norm = { id: string; doc: string };

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (path: string) => JSON.parse(readFileSync(`${root}${path}`, "utf8"));
const plan: { rules: Planned[]; families: Record<string, string> } = read("rules/plan.json");
const areas = [
  "cli",
  "edge-integrations",
  "guide-core",
  "pages-routing",
  "platform",
  "reference",
  "services",
];
const docOf = new Map(
  areas.flatMap((area) =>
    (read(`norms/${area}.json`).norms as Norm[]).map((norm) => [norm.id, norm.doc] as const),
  ),
);

/** `docs/rules.md`: every rule, by family, with what it holds and the docs pages it rests on. */
export function rulesDoc(): string {
  const lines = [
    "# Rules",
    "",
    "Generated by `scripts/rules-doc.ts` from the rules themselves. Each rule is `void/<name>`.",
    "The pages are those of Void's docs whose statements the rule enforces (`norms/*.json` has the exact lines).",
    "",
  ];
  for (const [family, summary] of Object.entries(plan.families)) {
    const members = plan.rules.filter((rule) => rule.family === family && rule.name in rules);
    if (members.length === 0) continue;
    lines.push(
      `## ${family}`,
      "",
      summary,
      "",
      "| Rule | Holds | Applies to | Docs |",
      "|---|---|---|---|",
    );
    for (const { name } of members.toSorted((a, b) => a.name.localeCompare(b.name))) {
      const docs = rules[name]?.meta.docs;
      if (!docs) continue;
      const pages = [...new Set(docs.norms.map((id) => docOf.get(id) ?? "?"))].toSorted();
      const scope =
        docs.scope === "void"
          ? "native Void apps"
          : docs.scope === "any"
            ? "every app"
            : docs.scope.replace("framework:", "").replaceAll(",", ", ");
      lines.push(
        `| \`${name}\` | ${docs.description.replaceAll("|", "\\|")} | ${scope} | ${pages.map((page) => `\`${page}\``).join(", ")} |`,
      );
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.stdout.write(rulesDoc());
